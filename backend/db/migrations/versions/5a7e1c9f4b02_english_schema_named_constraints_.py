def _fk_name(table: str, column: str, referred: str) -> str:
    return f"fk_{table}_{column}_{referred}"


def _index_name(table: str, column: str) -> str:
    return f"ix_{table}_{column}"


def _rename_values(table: str, column: str, pairs, reverse: bool = False) -> None:
    for old, new in pairs:
        source, target = (new, old) if reverse else (old, new)
        op.execute(f"UPDATE {table} SET {column} = '{target}' WHERE {column} = '{source}'")


def upgrade() -> None:
    """German schema -> English, plus indexes, checks and enforced deletes."""
    # Foreign keys go first: dropping them before the renames means the
    # recreate below can address every table and column by its new name.
    for table, _, _, _, name in OLD_FOREIGN_KEYS:
        op.drop_constraint(name, table, type_="foreignkey")

    for old, new in TABLES:
        op.rename_table(old, new)
    for table, columns in COLUMNS.items():
        for old, new in columns:
            op.alter_column(table, old, new_column_name=new)
    for table, old, new in PK_UQ_RENAMES:
        op.execute(f'ALTER TABLE {table} RENAME CONSTRAINT "{old}" TO "{new}"')

    # A Session still marked "laufend" never finished; see the note above.
