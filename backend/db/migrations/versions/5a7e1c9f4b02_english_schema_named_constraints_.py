    _rename_values("session", "status", SESSION_STATUS)
    _rename_values("turn", "speaker", SPEAKER)
    _rename_values("feedback_point", "kind", POINT_KIND)
    _rename_values("analysis_job", "kind", JOB_KIND)

    # New columns are NOT NULL but the tables can already hold rows, so each is
    # added nullable, backfilled, then tightened. The backfills are the values
    # the seed writes anyway (provision.py runs at every startup and corrects
    # them), not invented data: 'de' and 'de_male' are what the only Persona in
    # personas.py carries.
    op.add_column("persona", sa.Column("language_code", sa.String(8), nullable=True))
    op.add_column("persona", sa.Column("tts_voice", sa.String(60), nullable=True))
    op.add_column("persona", sa.Column("kugelaudio_voice_id", sa.Integer(), nullable=True))
    op.execute("UPDATE persona SET language_code = 'de' WHERE language_code IS NULL")
    op.execute("UPDATE persona SET tts_voice = 'de_male' WHERE tts_voice IS NULL")
    op.alter_column("persona", "language_code", existing_type=sa.String(8), nullable=False)
    op.alter_column("persona", "tts_voice", existing_type=sa.String(60), nullable=False)

    op.add_column("scenario", sa.Column("active", sa.Boolean(), nullable=True))
    op.execute("UPDATE scenario SET active = true WHERE active IS NULL")
    op.alter_column("scenario", "active", existing_type=sa.Boolean(), nullable=False)

    for table, column, nullable in TIMESTAMPS:
        op.alter_column(table, column, type_=sa.DateTime(timezone=True),
                        existing_type=sa.DateTime(), existing_nullable=nullable)

    for table, column, referred, referred_column, ondelete in FOREIGN_KEYS:
        op.create_foreign_key(_fk_name(table, column, referred), table, referred,
                              [column], [referred_column], ondelete=ondelete)
    for table, column in INDEXED_FK_COLUMNS:
        op.create_index(_index_name(table, column), table, [column])
    for table, name, condition in CHECKS:
        op.create_check_constraint(name, table, condition)


